// Embeds auditfile-spec/generated/ (fetched into spec/ by tools/fetch-spec.ps1) into src/generated/spec.js,
// so the reader needs no file system at runtime. Override the location with SPEC_ROOT=<path>.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specRoot = resolve(root, process.env.SPEC_ROOT ?? 'spec');
const generated = join(specRoot, 'generated');

try {
    statSync(join(generated, 'registry.json'));
} catch {
    console.error(`auditfile-spec not found in '${specRoot}'. Run: pwsh tools/fetch-spec.ps1`);
    process.exit(1);
}

function* walk(folder) {
    for (const entry of readdirSync(folder, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
        const path = join(folder, entry.name);
        if (entry.isDirectory()) {
            yield* walk(path);
        } else if (/\.(json|xsd)$/.test(entry.name)) {
            yield path;
        }
    }
}

const lock = JSON.parse(readFileSync(join(root, 'spec.lock.json'), 'utf8'));
const lines = [
    '// Generated by tools/embed-spec.mjs from auditfile-spec/generated/. Do not edit.',
    `export const spec = ${JSON.stringify({ repository: lock.repository, tag: lock.tag, commit: lock.commit })};`,
    'export const files = new Map([',
];

let count = 0;
for (const path of walk(generated)) {
    const name = relative(generated, path).split(sep).join('/');
    lines.push(`    [${JSON.stringify(name)}, ${JSON.stringify(readFileSync(path, 'utf8'))}],`);
    count++;
}

lines.push(']);', '');
mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'src', 'generated', 'spec.js'), lines.join('\n'));
console.log(`Embedded ${count} files from ${relative(root, generated) || generated}.`);
